// Exported so callers name them without repeating the strings.
const (
	DefaultFile        = "default.nix"
	HardwareConfigFile = "hardware-configuration.nix"
	BootFile           = "boot.nix"
	// ScopeModulesDir holds a host's or a machine's own units and its selection.
	ScopeModulesDir = "modules"

	machineSelectionStarter = "starters/machine-selection.nix"

	hardwareConfigNote = " (generated by nixos-generate-config; luxos never rewrites it)"
	bootNote           = " (review it; luxos never rewrites it)"

	missingMachineLink = "the modules/machine link is missing; create it with: luxos rebuild build"
)

// ErrNoMachineLink is a config no rebuild has linked to this computer yet.
var ErrNoMachineLink = errors.New(missingMachineLink)

// SelectionPath is the selection of the host or machine folder scopeDir.
func SelectionPath(scopeDir string) string {
	return filepath.Join(scopeDir, ScopeModulesDir, DefaultFile)
}

// MachineDir returns this computer's folder, keyed by its product_uuid.
func MachineDir(sysDir, machinesRoot string) (string, error) {
	key, err := hardware.Key(sysDir)
	if err != nil {
		return "", err
	}
	return filepath.Join(machinesRoot, key), nil
}

// LinkedMachineDir returns this computer's folder as rebuild recorded it in
// the modules/machine link. It needs no root.
func LinkedMachineDir(modulesDir string) (string, error) {
	real, err := filepath.EvalSymlinks(filepath.Join(modulesDir, MachineLinkName))
	if errors.Is(err, fs.ErrNotExist) {
		return "", ErrNoMachineLink
	}
	if err != nil {
		return "", err
	}
	return filepath.Dir(real), nil
}

// Machines lists the keys under machinesRoot holding a selection, sorted.
func Machines(machinesRoot string) ([]string, error) {
	return scopeFolders(machinesRoot)
}

// EnsureMachine creates this computer's folder and whichever of
// hardware-configuration.nix, modules/boot.nix and modules/default.nix are
// missing, then validates it. Existing files are never rewritten.
func EnsureMachine(out *ui.Progress, p paths.Paths) (string, error) {
	dir, err := MachineDir(p.Sys, p.Machines)
	if err != nil {
		return "", err
	}
	out.Printf("Ensuring %s...\n", dir)
	if err := MkdirAll(filepath.Join(dir, ScopeModulesDir)); err != nil {
		return "", err
	}

	hwConfig := filepath.Join(dir, HardwareConfigFile)
	created, err := ensureHardwareConfig(hwConfig)
	if err != nil {
		return "", err
	}
	if created {
		out.Changef("  created: %s%s", hwConfig, hardwareConfigNote)
	}

	bootPath := filepath.Join(dir, ScopeModulesDir, BootFile)
	if created, err = ensureBoot(bootPath, p.Sys, p.Dev, p.Mounts); err != nil {
		return "", err
	}
	if created {
		out.Changef("  created: %s%s", bootPath, bootNote)
	}

	if created, err = ensureMachineSelection(dir); err != nil {
		return "", err
	}
	if created {
		out.Changef("  created: %s", SelectionPath(dir))
	}

	if err := ValidateMachine(dir); err != nil {
		return "", err
	}
	return dir, out.Err()
}

// ensureMachineSelection writes the seed selection when dir has none.
func ensureMachineSelection(dir string) (bool, error) {
	if err := MkdirAll(filepath.Join(dir, ScopeModulesDir)); err != nil {
		return false, err
	}
	seed, err := templates.File(machineSelectionStarter)
	if err != nil {
		return false, err
	}
	return CreateFile(SelectionPath(dir), seed)
}

// ensureHardwareConfig writes hardwareFile from nixos-generate-config when
// nothing exists at that path, and reports whether it did. An existing entry
// is never read or rewritten.
func ensureHardwareConfig(hardwareFile string) (created bool, err error) {
	if _, err := os.Lstat(hardwareFile); err == nil {
		return false, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}
	content, err := nix.ShowHardwareConfig()
	if err != nil {
		return false, fmt.Errorf("cannot generate %s: %w\nrun by hand: nixos-generate-config --show-hardware-config > %s", hardwareFile, err, hardwareFile)
	}
	if err := WriteFile(hardwareFile, content); err != nil {
		return false, fmt.Errorf("config.ensureHardwareConfig: write %s: %w", hardwareFile, err)
	}
	return true, nil
}

// ensureBoot writes bootFile from boot loader detection when nothing exists
// at that path, and reports whether it did. An existing entry of any kind is
// left alone. A detection failure is a hard error naming bootFile.
func ensureBoot(bootFile, sysDir, devDir, mountsFile string) (created bool, err error) {
	if _, err := os.Lstat(bootFile); err == nil {
		return false, nil
	} else if !os.IsNotExist(err) {
		return false, fmt.Errorf("config.ensureBoot: stat %s: %w", bootFile, err)
	}

	loader, err := hardware.DetectBoot(sysDir, devDir, mountsFile)
	if err != nil {
		return false, fmt.Errorf("cannot detect the boot loader: %s\nwrite %s by hand to configure the boot loader", err, bootFile)
	}

	content, err := hardware.RenderBoot(loader)
	if err != nil {
		return false, err
	}

	if err := WriteFile(bootFile, content); err != nil {
		return false, fmt.Errorf("config.ensureBoot: write %s: %w", bootFile, err)
	}

	return true, nil
}

// ValidateMachine checks the files a machine folder must hold; any other
// entry is allowed. Every problem is reported, sorted, in one error shaped
// like ValidateHost's: "missing <name>" or "<name> is not a regular file".
func ValidateMachine(dir string) error {
	var problems []string
	for _, name := range []string{
		HardwareConfigFile,
		filepath.Join(ScopeModulesDir, DefaultFile),
		filepath.Join(ScopeModulesDir, BootFile),
	} {
		info, err := os.Stat(filepath.Join(dir, name))
		switch {
		case os.IsNotExist(err):
			problems = append(problems, "missing "+name)
		case err != nil || !info.Mode().IsRegular():
			problems = append(problems, name+" is not a regular file")
		}
	}
	return problemsError("invalid machine folder "+dir, problems)
}
