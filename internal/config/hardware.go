// Exported so callers name them without repeating the strings.
const (
	DefaultFile        = "default.nix"
	HardwareConfigFile = "hardware-configuration.nix"
	BootFile           = "boot.nix"
	HardwareFile       = "hardware.nix"

	HardwareUnitName = "hardware-support"
	HardwareUnitPath = "local/" + HardwareUnitName

	hardwareTemplate        = "starters/hardware.nix"
	hardwareDefaultTemplate = "starters/hardware-default.nix"

	hardwareConfigNote = " (generated by nixos-generate-config; luxos never rewrites it)"
	bootNote           = " (review it; luxos never rewrites it)"
)

// HardwareDir returns this computer's hardware folder, keyed by its product_uuid.
func HardwareDir(sysDir, hardwareRoot string) (string, error) {
	key, err := hardware.Key(sysDir)
	if err != nil {
		return "", err
	}
	return filepath.Join(hardwareRoot, key), nil
}

// EnsureHardware creates this computer's hardware folder and whichever of its
// files are missing, then validates it. Existing files are never rewritten.
func EnsureHardware(w io.Writer, p paths.Paths) (string, error) {
	out := ui.NewProgress(w)
	hwDir, err := HardwareDir(p.Sys, p.HardwareRoot)
	if err != nil {
		return "", err
	}
	out.Printf("Ensuring %s...\n", hwDir)
	if err := MkdirAll(hwDir); err != nil {
		return "", err
	}

	hwConfig := filepath.Join(hwDir, HardwareConfigFile)
	created, err := ensureHardwareConfig(hwConfig)
	if err != nil {
		return "", err
	}
	if created {
		out.Printf("  created: %s%s\n", hwConfig, hardwareConfigNote)
	}

	bootPath := filepath.Join(hwDir, BootFile)
	created, err = ensureBoot(bootPath, p.Sys, p.Mounts)
	if err != nil {
		return "", err
	}
	if created {
		out.Printf("  created: %s%s\n", bootPath, bootNote)
	}

	for _, f := range []struct{ name, template string }{
		{HardwareFile, hardwareTemplate},
		{DefaultFile, hardwareDefaultTemplate},
	} {
		tmpl, err := templates.File(f.template)
		if err != nil {
			return "", err
		}
		path := filepath.Join(hwDir, f.name)
		created, err = CreateFile(path, tmpl)
		if err != nil {
			return "", err
		}
		if created {
			out.Printf("  created: %s\n", path)
		}
	}

	if err := ValidateHardware(hwDir); err != nil {
		return "", err
	}
	return hwDir, out.Err()
}

// ensureHardwareConfig writes hardwareFile from nixos-generate-config when
// nothing exists at that path, and reports whether it did. An existing entry
// is never read or rewritten.
func ensureHardwareConfig(hardwareFile string) (created bool, err error) {
	if _, err := os.Lstat(hardwareFile); err == nil {
		return false, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}
	content, err := nix.ShowHardwareConfig()
	if err != nil {
		return false, fmt.Errorf("cannot generate %s: %w\nrun by hand: nixos-generate-config --show-hardware-config > %s", hardwareFile, err, hardwareFile)
	}
	if err := WriteFile(hardwareFile, content); err != nil {
		return false, fmt.Errorf("config.ensureHardwareConfig: write %s: %w", hardwareFile, err)
	}
	return true, nil
}

// ensureBoot writes bootFile from boot loader detection when nothing exists
// at that path, and reports whether it did. An existing entry of any kind is
// left alone. A detection failure is a hard error naming bootFile.
func ensureBoot(bootFile, sysDir, mountsFile string) (created bool, err error) {
	if _, err := os.Lstat(bootFile); err == nil {
		return false, nil
	} else if !os.IsNotExist(err) {
		return false, fmt.Errorf("config.ensureBoot: stat %s: %w", bootFile, err)
	}

	loader, err := hardware.DetectBoot(sysDir, mountsFile)
	if err != nil {
		return false, fmt.Errorf("cannot detect the boot loader: %s\nwrite %s by hand to configure the boot loader", err, bootFile)
	}

	content, err := hardware.RenderBoot(loader)
	if err != nil {
		return false, err
	}

	if err := WriteFile(bootFile, content); err != nil {
		return false, fmt.Errorf("config.ensureBoot: write %s: %w", bootFile, err)
	}

	return true, nil
}

// Any other entry is allowed. Every problem is reported, sorted, in one error
// shaped like ValidateHost's: "missing <name>" or "<name> is not a regular file".
func ValidateHardware(dir string) error {
	var problems []string
	for _, name := range []string{DefaultFile, HardwareConfigFile, BootFile, HardwareFile} {
		info, err := os.Stat(filepath.Join(dir, name))
		switch {
		case os.IsNotExist(err):
			problems = append(problems, "missing "+name)
		case err != nil || !info.Mode().IsRegular():
			problems = append(problems, name+" is not a regular file")
		}
	}
	return problemsError("invalid hardware folder "+dir, problems)
}
